export const analyzeMedicalCase = async (
  patientData: Partial<PatientCase>,
  settings: SystemSettings
): Promise<{ diagnosis: StructuredDiagnosis, sources: any[] }> => {
  try {
    // 1. Try backend server API
    const response = await fetch("/api/analyze-case", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ patientData, settings })
    });
    
    if (response.ok) {
      return await response.json();
    }
    
    const errData = await response.json().catch(() => ({}));
    throw new Error(errData.error || "Failed to analyze clinical case");
  } catch (e: any) {
    console.warn("Express backend API call failed or unavailable. Initiating browser-side fallback...", e);
    
    // 2. Client-side direct call to Gemini if API key is provided in settings
    const envKey = typeof process !== "undefined" ? process.env?.GEMINI_API_KEY : undefined;
    const apiKey = settings?.apiKey || envKey;
    const hasKey = apiKey && apiKey.trim() !== "" && apiKey.length > 10;
    
    if (hasKey) {
      try {
        console.log("Running Gemini clinical analysis directly on client-side...");
        const ai = new GoogleGenAI({ apiKey });
        const systemInstruction = getModelSpecificInstructions(settings.model, settings.personality);
        const prompt = getModelSpecificPrompt(settings.model, patientData, settings.thinkingBudget, settings.deepThinking);
        
        const parts: any[] = [{ text: prompt }];
        if (patientData.images && patientData.images.length > 0) {
          patientData.images.forEach((img: string) => {
            if (img.includes(',')) {
              parts.push({
                inlineData: {
                  mimeType: 'image/jpeg',
                  data: img.split(',')[1]
                }
              });
            }
          });
        }
        
        const config: any = {
          systemInstruction,
          responseMimeType: "application/json",
          responseSchema: {
            type: Type.OBJECT,
            properties: {
              conditionName: { type: Type.STRING },
              conditionSymptoms: { type: Type.ARRAY, items: { type: Type.STRING } },
              conditionCauses: { type: Type.ARRAY, items: { type: Type.STRING } },
              summary: { type: Type.STRING },
              detailedAnalysis: { type: Type.STRING },
              severity: { type: Type.STRING, enum: ["منخفضة", "متوسطة", "مرتفعة", "حرجة"] },
              severityReasoning: { type: Type.STRING },
              confidenceScore: { type: Type.NUMBER },
              imageFindings: { type: Type.STRING },
              specialistReferral: { type: Type.STRING },
              differentialDiagnosis: {
                type: Type.ARRAY,
                items: {
                  type: Type.OBJECT,
                  properties: {
                    condition: { type: Type.STRING },
                    probability: { type: Type.NUMBER },
                    reasoning: { type: Type.STRING },
                    symptoms: { type: Type.ARRAY, items: { type: Type.STRING } },
                    causes: { type: Type.ARRAY, items: { type: Type.STRING } }
                  }
                }
              },
              treatmentPlan: { type: Type.ARRAY, items: { type: Type.STRING } },
              dietaryAdvice: { type: Type.ARRAY, items: { type: Type.STRING } },
              herbalMedicine: { type: Type.ARRAY, items: { type: Type.STRING } },
              physicalTherapy: { type: Type.ARRAY, items: { type: Type.STRING } },
              lifestyleChanges: { type: Type.ARRAY, items: { type: Type.STRING } },
              suggestedTests: { type: Type.ARRAY, items: { type: Type.STRING } },
              urgentWarnings: { type: Type.ARRAY, items: { type: Type.STRING } },
              preventionTips: { type: Type.ARRAY, items: { type: Type.STRING } },
              recommendations: { type: Type.ARRAY, items: { type: Type.STRING } },
              generalInfo: { type: Type.STRING },
              labResultsAnalysis: { type: Type.STRING }
            },
            required: ["conditionName", "summary", "detailedAnalysis", "severity", "severityReasoning", "confidenceScore", "treatmentPlan", "dietaryAdvice", "physicalTherapy", "lifestyleChanges", "labResultsAnalysis", "recommendations", "generalInfo"]
          }
        };
        
        if (settings.googleSearch && (settings.model.includes('pro') || settings.model.includes('image-preview'))) {
          config.tools = [{ googleSearch: {} }];
        }
        
        if (settings.deepThinking && settings.model.includes('gemini-3')) {
          if (!settings.model.includes('pro') && !settings.model.includes('lite')) {
            config.thinkingConfig = { 
              thinkingBudgetTokens: settings.thinkingBudget 
            };
          }
        }
        
        let modelName: string = settings.model;
        if (modelName === ModelType.PRO) modelName = 'gemini-3.1-pro-preview';
        else if (modelName === ModelType.FLASH) modelName = 'gemini-3.5-flash';
        else if (modelName === ModelType.LITE) modelName = 'gemini-3.1-flash-lite-preview';
        
        const response = await ai.models.generateContent({
          model: modelName,
          contents: { parts },
          config
        });
        
        const text = response.text?.replace(/```json/g, "").replace(/```/g, "").trim() || '{}';
        return {
          diagnosis: JSON.parse(text),
          sources: response.candidates?.[0]?.groundingMetadata?.groundingChunks || []
        };
      } catch (geminiError) {
        console.error("Direct browser-side Gemini call failed. Falling back to free local simulation...", geminiError);
      }
    }
    
    // 3. Fallback to free smart simulation engine if API key is not set or direct client call fails
    console.log("Activating local smart clinical diagnosis simulator (FREE/OFFLINE)...");
    const simulatedDiag = getSimulatedDiagnosis(patientData);
    return {
      diagnosis: simulatedDiag,
      sources: []
    };
  }
};

export const consolidateMedicalCases = async (
  cases: PatientCase[],
  settings: SystemSettings
): Promise<{ synthesis: string }> => {
  try {
    const response = await fetch("/api/consolidate-cases", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ cases, settings })
    });
    
    if (response.ok) {
      return await response.json();
    }
    
    const errData = await response.json().catch(() => ({}));
    throw new Error(errData.error || "Failed to consolidate clinical cases");
  } catch (e: any) {
    console.warn("Express backend API call for consolidation failed or unavailable. Initiating fallback...", e);
    
    const envKey = typeof process !== "undefined" ? process.env?.GEMINI_API_KEY : undefined;
    const apiKey = settings?.apiKey || envKey;
    const hasKey = apiKey && apiKey.trim() !== "" && apiKey.length > 10;
    
    if (hasKey) {
      try {
        console.log("Running Gemini consolidation directly on client side...");
        const ai = new GoogleGenAI({ apiKey });
        
        let modelName: string = settings?.model || "gemini-3.1-pro-preview";
        if (modelName === ModelType.PRO) modelName = 'gemini-3.1-pro-preview';
        else if (modelName === ModelType.FLASH) modelName = 'gemini-3.5-flash';
        else if (modelName === ModelType.LITE) modelName = 'gemini-3.1-flash-lite-preview';
        
        const casesSummary = cases.map((c: any, index: number) => {
          return `
            الحالة #${index + 1}:
            - الاسم: ${c.name}
            - العمر: ${c.age} | الجنس: ${c.gender}
            - التاريخ: ${c.date}
            - الأعراض: ${c.symptoms}
            - المؤشرات الحيوية: النبض ${c.vitals?.pulse || '--'}، الأكسجين ${c.vitals?.spo2 || '--'}%، الحرارة ${c.vitals?.temperature || '--'}°C، ضغط الدم ${c.vitals?.bloodPressure || '--/--'}
            - التشخيص السابق (إن وجد): ${c.diagnosis?.conditionName || 'بانتظار التحليل'}
            - ملخص التشخيص السريري: ${c.diagnosis?.summary || 'لا يوجد'}
          `;
        }).join("\n---\n");

        const systemInstruction = `أنت "كبير الأطباء الاستشاريين ومحلل البيانات السريرية" (Chief Medical Data Analyst).
مهمتك هي مراجعة وتجميع وتحليل ومقارنة قائمة من الحالات السريرية والتشخيصات الحرارية والفسيولوجية المتوفرة لدى الطبيب.
تقديم ملخص سريري تجميعي ذكي وقوي للغاية (Clinical Synthesis Report) باللغة العربية الفصحى الطبية الرصينة.`;

        const prompt = `الرجاء دراسة ومقارنة السجلات الطبية والتشخيصية التالية لتقديم تقرير تجميعي:\n${casesSummary}`;

        const response = await ai.models.generateContent({
          model: modelName,
          contents: prompt,
          config: {
            systemInstruction,
            temperature: 0.2
          }
        });
        
        return { synthesis: response.text || "لم يتم التمكن من استخراج التقرير التجميعي." };
      } catch (geminiError) {
        console.error("Direct client-side Gemini consolidation failed. Falling back to local synthesis...", geminiError);
      }
    }
    
    console.log("Running local consolidation simulation...");
    return { synthesis: getSimulatedConsolidation(cases) };
  }
};

export const startFollowUpChat = (patient: PatientCase, settings: SystemSettings, fallbackModelOverride?: string): any => {
  let history = patient.chatHistory || [];

  return {
    async sendMessageStream({ message }: { message: any }) {
      try {
        // Try the backend express server API first
        const response = await fetch("/api/chat-message", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            patient,
            settings,
            history,
            messageContent: message,
            fallbackModelOverride
          })
        });

        if (response.ok) {
          const data = await response.json();
          const fullText = data.text || "";

          const userText = typeof message === "string" ? message : (Array.isArray(message) ? message.find(p => p.text)?.text || "مرفق" : "مرفق");
          history.push({
            role: "user",
            text: userText,
            timestamp: new Date().toLocaleTimeString('ar-EG', { hour: '2-digit', minute: '2-digit' })
          });
          history.push({
            role: "model",
            text: fullText,
            timestamp: new Date().toLocaleTimeString('ar-EG', { hour: '2-digit', minute: '2-digit' })
          });

          return {
            async *[Symbol.asyncIterator]() {
              const chunks: string[] = [];
              let i = 0;
              while (i < fullText.length) {
                const len = Math.min(Math.floor(Math.random() * 8) + 4, fullText.length - i);
                chunks.push(fullText.slice(i, i + len));
                i += len;
              }
              for (const chunk of chunks) {
                await new Promise(resolve => setTimeout(resolve, Math.random() * 12 + 4));
                yield { text: chunk };
              }
            }
          };
        }
        
        throw new Error("Express backend chat API call failed");
      } catch (err) {
        console.warn("Express backend API chat message failed. Initiating fallbacks...", err);
        
        // Fallback strategy: Direct client browser or smart local chat simulation
        const envKey = typeof process !== "undefined" ? process.env?.GEMINI_API_KEY : undefined;
        const apiKey = settings?.apiKey || envKey;
        const hasKey = apiKey && apiKey.trim() !== "" && apiKey.length > 10;
        
        let fullText = "";
        const userText = typeof message === "string" ? message : (Array.isArray(message) ? message.find(p => p.text)?.text || "مرفق" : "مرفق");
        
        if (hasKey) {
          try {
            console.log("Running Gemini follow-up chat directly on client side...");
            const ai = new GoogleGenAI({ apiKey });
            
            let modelName: string = fallbackModelOverride || settings.model || 'gemini-3.1-pro-preview';
            if (modelName === 'gemini-3.1-flash-live-preview') {
              modelName = 'gemini-3.6-flash';
            }
            
            const clinicalContext = `
              [ملف المريض السريري]
              الاسم: ${patient.name} | العمر: ${patient.age} | الجنس: ${patient.gender}
              الأعراض الأولية (HPI): ${patient.symptoms}
              المؤشرات الحيوية: ضغط الدم ${patient.vitals?.bloodPressure} | النبض ${patient.vitals?.pulse} | الحرارة ${patient.vitals?.temperature} | الأكسجين ${patient.vitals?.spo2}
              
              [التشخيص المعتمد]
              التشخيص: ${patient.diagnosis?.conditionName}
              مستوى الخطورة: ${patient.diagnosis?.severity}
              الخطة العلاجية الحالية: ${patient.diagnosis?.treatmentPlan?.join('، ')}
            `;
            
            const systemInstruction = `أنت الآن الطبيب الاستشاري المباشر المشرف على حالة هذا المريض.
            السياق السريري للمريض:
            ${clinicalContext}
            
            تعليمات الرد (صارمة):
            1. أجب على أسئلة المريض أو الفريق الطبي بمهنية طبية عالية جداً.
            2. لا تتصرف أبداً كـ "ذكاء اصطناعي" أو "مساعد افتراضي"، بل كطبيب بشري خبير يتابع حالة مريضه في العيادة.
            3. اربط إجاباتك دائماً بحالة المريض الحالية، عمره، وتشخيصه المعتمد المذكور أعلاه.
            4. إذا سأل المريض عن دواء أو عرض جديد، قم بتحليله سريرياً بناءً على تاريخه المرضي.
            الأسلوب المعتمد: ${settings.personality}.`;
            
            const mappedHistory = history.map((msg: any) => {
              const parts: any[] = [{ text: msg.text }];
              if (msg.images && msg.images.length > 0) {
                msg.images.forEach((img: string) => {
                  if (img.includes(',')) {
                    parts.push({
                      inlineData: {
                        mimeType: img.substring(img.indexOf(':') + 1, img.indexOf(';')) || 'image/jpeg',
                        data: img.split(',')[1]
                      }
                    });
                  }
                });
              }
              return {
                role: msg.role === 'user' ? 'user' : 'model',
                parts
              };
            });
            
            const chatInstance = ai.chats.create({
              model: modelName,
              history: mappedHistory,
              config: { systemInstruction }
            });
            
            const response = await chatInstance.sendMessage({ message: userText });
            fullText = response.text || "";
          } catch (geminiError) {
            console.error("Direct client-side Gemini chat failed. Falling back to local simulator...", geminiError);
            fullText = getSimulatedChatResponse(patient, userText);
          }
        } else {
          console.log("Activating local follow-up chat simulator...");
          fullText = getSimulatedChatResponse(patient, userText);
        }

        // Save progress to patient chat history state
        history.push({
          role: "user",
          text: userText,
          timestamp: new Date().toLocaleTimeString('ar-EG', { hour: '2-digit', minute: '2-digit' })
        });
        history.push({
          role: "model",
          text: fullText,
          timestamp: new Date().toLocaleTimeString('ar-EG', { hour: '2-digit', minute: '2-digit' })
        });

        return {
          async *[Symbol.asyncIterator]() {
            const chunks: string[] = [];
            let i = 0;
            while (i < fullText.length) {
              const len = Math.min(Math.floor(Math.random() * 8) + 4, fullText.length - i);
              chunks.push(fullText.slice(i, i + len));
              i += len;
            }
            for (const chunk of chunks) {
              await new Promise(resolve => setTimeout(resolve, Math.random() * 12 + 4));
              yield { text: chunk };
            }
          }
        };
      }
    }
  };
};

export const generateSpeech = async (text: string, settings?: SystemSettings, voiceName?: string): Promise<string> => {
  try {
    const response = await fetch("/api/generate-speech", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ text, settings, voiceName })
    });

    if (response.ok) {
      const data = await response.json();
      return data.audioData || "";
    }
    
    throw new Error("Speech API call returned non-OK response");
  } catch (err) {
    console.warn("Express backend API call for speech generation failed. Initiating browser-side fallback...", err);
    
    const envKey = typeof process !== "undefined" ? process.env?.GEMINI_API_KEY : undefined;
    const apiKey = settings?.apiKey || envKey;
    const hasKey = apiKey && apiKey.trim() !== "" && apiKey.length > 10;
    
    if (hasKey) {
      try {
        console.log("Generating speech directly via Gemini on client side...");
        const ai = new GoogleGenAI({ apiKey });
        
        const cleanTextForTTS = (input: string): string => {
          if (!input) return "";
          let clean = input;
          clean = clean.replace(/(\d+)\s*%\s*/g, "$1 بالمئة ");
          clean = clean.replace(/%/g, " بالمئة ");
          clean = clean.replace(/\b(bpm|BPM)\b/gi, " نبضة في الدقيقة ");
          clean = clean.replace(/\b(mg|MG)\b/gi, " مليجرام ");
          clean = clean.replace(/\b(ml|ML)\b/gi, " مليلتر ");
          clean = clean.replace(/\b(kg|KG)\b/gi, " كيلوجرام ");
          clean = clean.replace(/\b(g|G)\b/gi, " جرام ");
          clean = clean.replace(/°\s*C/gi, " درجة مئوية ");
          clean = clean.replace(/\bCelsius\b/gi, " درجة مئوية ");
          clean = clean.replace(/\b(pH|PH)\b/g, " بي إتش ");
          clean = clean.replace(/[\u2600-\u27BF]|[\uE000-\uF8FF]|\uD83C[\uDC00-\uDFFF]|\uD83D[\uDC00-\uDFFF]|[\u2011-\u26FF]|\uD83E[\uDD10-\uDDFF]/g, "");
          clean = clean.replace(/\*\*/g, " ");
          clean = clean.replace(/\*/g, " ");
          clean = clean.replace(/#/g, " ");
          clean = clean.replace(/`/g, " ");
          clean = clean.replace(/~/g, " ");
          clean = clean.replace(/_+/g, " ");
          clean = clean.replace(/[●•\-+]/g, " ");
          clean = clean.replace(/[a-zA-Z]/g, " ");
          clean = clean.replace(/[\[\]\(\)\{\}]/g, " ");
          clean = clean.replace(/[:؛;!؟?]/g, "، ");
          clean = clean.replace(/[#@$^&*|\\/=<>]/g, " ");
          clean = clean.replace(/\s+/g, " ");
          return clean.trim();
        };

        const sanitizedText = cleanTextForTTS(text);
        if (!sanitizedText) return "";

        const response = await ai.models.generateContent({
          model: "gemini-3.1-flash-tts-preview",
          contents: [{ parts: [{ text: sanitizedText }] }],
          config: {
            responseModalities: [Modality.AUDIO],
            speechConfig: { 
              voiceConfig: { 
                prebuiltVoiceConfig: { voiceName: voiceName || 'Puck' } 
              } 
            },
          },
        });
        return response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data || "";
      } catch (e) {
        console.error("Direct browser speech generation failed.", e);
      }
    }
    
    // Returning empty string triggers browser native WebSpeech Synthesis (automatic fallback in UI)
    return "";
  }
};
